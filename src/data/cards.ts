export function getCardById(id: string): CardData | undefined {
 return ALL_CARDS.find((card) => card.id === id);
}

export function getCardsBySide(side: 'plant' | 'zombie' | Team): CardData[] {
 if (side === 'plant' || side === 'plants') {
 return PLANT_CARDS;
 }
 return ZOMBIE_CARDS;
}

export function getCardsByType(type: CardType): CardData[] {
 return ALL_CARDS.filter((card) => card.type === type);
}

export function getAllCards(): CardData[] {
 return ALL_CARDS;
}

export function getAllHeroes(): HeroData[] {
 return ALL_HEROES;
}

export function getHeroById(id: string): HeroData | undefined {
 return ALL_HEROES.find((hero) => hero.id === id);
}

export function getInitialDeck(side: 'plant' | 'zombie' | Team): CardData[] {
 const pool = getCardsBySide(side);
 return pool.slice(0, 10);
}

export function getCardsByRarity(rarity: Rarity, side?: 'plant' | 'zombie' | Team): CardData[] {
 const pool = side ? getCardsBySide(side) : ALL_CARDS;
 return pool.filter((card) => card.rarity === rarity);
}

export function getCardsByTribe(tribeKeyword: string, side?: 'plant' | 'zombie' | Team): CardData[] {
 const pool = side ? getCardsBySide(side) : ALL_CARDS;
 const keyword = tribeKeyword.toLowerCase();
 return pool.filter((card) => card.tribe && card.tribe.toLowerCase().includes(keyword));
}

export function getCardsByHeroClass(heroClass: HeroClass, side?: 'plant' | 'zombie' | Team): CardData[] {
 const pool = side ? getCardsBySide(side) : ALL_CARDS;
 return pool.filter((card) => card.heroClass === heroClass);
}

